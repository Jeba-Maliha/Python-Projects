import streamlit as st
import random

st.title("Hangman Game")
st.write("Guess the fruit!")

fruits = [
    "apple", "banana", "mango", "strawberry",
    "orange", "grape", "pineapple", "apricot",
    "lemon", "coconut", "watermelon", "cherry",
    "papaya", "berry", "peach", "lychee", "muskmelon"
]

if "word" not in st.session_state:
    st.session_state.word = random.choice(fruits)
    st.session_state.guessed = []
    st.session_state.attempts = 6

word = st.session_state.word

display_word = " ".join(
    letter if letter in st.session_state.guessed else "_"
    for letter in word
)

st.subheader(display_word)
st.write(f"Attempts remaining: {st.session_state.attempts}")

guess = st.text_input("Enter a letter:", max_chars=1).lower()

if st.button("Guess"):
    if not guess or not guess.isalpha():
        st.warning("Please enter a letter.")
    elif guess in st.session_state.guessed:
        st.warning("You already guessed that letter.")
    else:
        st.session_state.guessed.append(guess)

        if guess not in word:
            st.session_state.attempts -= 1

        st.rerun()

won = all(
    letter in st.session_state.guessed for letter in word
)

if won:
    st.success("Congratulations! You won!")
elif st.session_state.attempts == 0:
    st.error(f"Game Over! The word was {word}.")

st.write("Guessed letters:", ", ".join(st.session_state.guessed))

if st.button("New Game"):
    st.session_state.word = random.choice(fruits)
    st.session_state.guessed = []
    st.session_state.attempts = 6
    st.rerun()